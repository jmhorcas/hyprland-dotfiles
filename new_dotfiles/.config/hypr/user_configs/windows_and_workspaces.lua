-- Hyprland-run windowrule
hl.window_rule({
    name  = "move-hyprland-run",
    match = { class = "hyprland-run" },

    move  = "20 monitor_h-120",
    float = true,
})

-- Picture-in-Picture: Automatically floats browser mini-players (Firefox/Chrome), 
-- moves them to the top-right corner, scales them, and pins them to stay visible across all workspaces.
hl.window_rule({
    name  = "Picture-in-Picture",
    match = { title = "^(Picture-in-Picture)$" },
    
    float = true,
    move  = "72% 7%",
    pin   = true,
    size  = "25% 25%",
})
